// Generates src/styles/tokens.css from the brand kit (brand.json) and the
// app-only tokens (ui.json). Run `pnpm tokens` after changing either file;
// test/tokens.test.ts fails if the CSS is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const read = (p) => JSON.parse(readFileSync(here(p), "utf8"));

export function renderTokensCss(brand, ui) {
  const theme = (name) => ({ ...brand.color[name], ...ui.color[name] });
  const vars = (obj, indent) =>
    Object.entries(obj)
      .map(([k, v]) => `${indent}--ww-${k}: ${v};`)
      .join("\n");
  const shared = {
    "font-display": brand.font.display,
    "font-body": brand.font.body,
    "font-mono": "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace",
    ...Object.fromEntries(Object.entries(brand.radius).map(([k, v]) => [`radius-${k}`, v])),
  };
  const dark = theme("dark");
  return `/* Generated by scripts/build-tokens.mjs. Do not edit by hand. */
:root {
  color-scheme: light;
${vars(theme("light"), "  ")}
${vars(shared, "  ")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${vars(dark, "    ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${vars(dark, "  ")}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = renderTokensCss(read("../src/tokens/brand.json"), read("../src/tokens/ui.json"));
  writeFileSync(here("../src/styles/tokens.css"), css);
  console.log("wrote src/styles/tokens.css");
}
